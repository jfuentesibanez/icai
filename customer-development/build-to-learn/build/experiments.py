"""The 24 experiment cards. Each one feeds its tile on the level slide and its own card slide.

letters: D, F, V (or "!" for "not evidence"). effort and evidence are qualitative on purpose.
"""

LEVELS = {
    "say": (1, "Say", "They talk, you listen"),
    "show": (2, "Show", "They see it, but cannot use it yet"),
    "fake": (3, "Fake", "They try to use it. Behind the screen, you or an AI do the work."),
    "real": (4, "Real", "They use it, come back and pay"),
}

E = []


def exp(level, id, name, letters, short, tools_short, what, steps, measure, example, ai, watch, tools,
        effort, evidence, src=None):
    E.append(dict(level=level, id=id, name=name, letters=letters, short=short, tools_short=tools_short,
                  what=what, steps=steps, measure=measure, example=example, ai=ai, watch=watch,
                  tools=tools, effort=effort, evidence=evidence, src=src))


